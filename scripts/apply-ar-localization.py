def main():
    path = Path("Modules/Platform/Platform.Localization/Resources/Resource.ar-EG.resx")
    tree = ET.parse(path)
    root = tree.getroot()
    updated = 0
    for el in root.findall("data"):
        name = el.get("name")
        if name not in TRANSLATIONS:
            continue
        val_el = el.find("value")
        if val_el is None:
            val_el = ET.SubElement(el, "value")
        if val_el.text == TRANSLATIONS[name]:
            continue
        val_el.text = TRANSLATIONS[name]
        updated += 1
    tree.write(path, encoding="utf-8", xml_declaration=True)
    print(f"Updated {updated} keys in {path}")
    missing = set(TRANSLATIONS) - {el.get("name") for el in root.findall("data")}
    if missing:
        raise SystemExit(f"Keys in TRANSLATIONS not in resx: {sorted(missing)}")


if __name__ == "__main__":
    main()
